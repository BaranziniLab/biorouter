//! Rule 3: stored absolute paths that pointed into the legacy folder.
//!
//! Several stores keep absolute paths into Biorouter's own folder, and four of
//! them break silently when the folder moves and the path does not: a resumed
//! chat starts its `.brxt` extensions from the per-chat snapshot of
//! `uv run --directory <path>`, every knowledge base drops out of the list,
//! the Crew vault refuses to unlock (`daemon-profile.json` must equal the
//! canonical config dir), and a marketplace extension's privacy tier falls
//! back to the name match because its provenance `install_dir` no longer
//! equals the config argument byte for byte.
//!
//! # How a string is rewritten
//!
//! Only the author segment changes. A stored path matches when, compared
//! character by character with the legacy root, letters agree ignoring case
//! and every separator is either `\` or `/` (Windows accepts both, and users
//! write both). The character before it must not be a letter or digit, and the
//! one after it must end the path or start the next segment, so a sibling such
//! as `<legacy author>2` or `biorouter-old` never matches. The base before the
//! author keeps the spelling it was stored with, case included, so a
//! canonical `\\?\C:\...` value stays canonical.
//!
//! The legacy root is matched in two spellings: the base as the environment
//! names it (`%APPDATA%`), and the base as `fs::canonicalize` returns it, which
//! is how `daemon-profile.json` stores its config dir and a directory
//! permission grant its directory. The two differ by more than the `\\?\`
//! prefix whenever the base is not a plain local path: a roaming profile
//! redirected to a share (`\\fs1\home$\...` against `\\?\UNC\fs1\home$\...`),
//! a mapped drive (which canonicalizes to its UNC path), or a junction or
//! `subst` drive in the profile path.
//!
//! Each spelling writes the author the way its own kind of path now names it.
//! The environment's spelling writes [`APP_AUTHOR`], as `Paths` builds it. The
//! canonical spelling writes the author folder's name as it is on disk, read
//! back through `fs::canonicalize` ([`author_on_disk`]): when an author folder
//! that differs only in case already existed (another tool's `ucsf`), the move
//! put the tree inside it, and the canonical paths those stores are compared
//! with say `ucsf`, byte for byte.
//!
//! # How a file is rewritten
//!
//! On the file's TEXT, so every byte outside the matched author segments is
//! kept (comments, key order, quoting and indentation included). The text is
//! read the way its parser reads it ([`Reading`]): in JSON every `\` starts an
//! escape, so a separator is `\\` or `\/`, a path never starts inside an
//! escape, and the character before a path is the one an escape spells (`\n`
//! is a line break, not the letter `n`). YAML text is tried both ways, because
//! only a double-quoted scalar has escapes and the text alone does not say
//! which style a position is in. Before anything is written, the result is
//! checked against the parsed document: parsing the new text must give
//! exactly what rewriting every string of the old parse gives. A file that
//! fails the check is left as it was and named in the log. A changed file is
//! written to a temporary file beside it and renamed over it.
//!
//! Transcripts, logs, backups (`*.bak*`) and venvs are deliberately left
//! alone: they are history, or regenerated by `uv`.

use super::{AppRoot, APP_AUTHOR, APP_NAME, LEGACY_APP_AUTHOR, MOVE_MARKER};
use std::fs;
use std::io::{self, Write};
use std::ops::Range;
use std::path::{Path, PathBuf};
use std::time::Duration;

/// How a document's text is parsed when the rewrite is checked.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    Json,
    Yaml,
}

/// What a match is made in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Source {
    /// A parsed string value.
    Value,
    /// A document's raw text.
    Text(Format),
}

/// How the characters around and inside a path are read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Reading {
    /// Every character means itself: a parsed value, or a YAML scalar that is
    /// plain, single-quoted, literal or folded. A separator is one `\` or `/`.
    Literal,
    /// A `\` starts an escape: JSON text, or a double-quoted YAML scalar. A
    /// separator is `\\`, `\/` or `/`; a path never starts in the middle of an
    /// escape, and the character before it is the one an escape spells.
    Escaped,
}

impl Source {
    /// The readings tried at each position, in order. A YAML position may be
    /// either; where the two would disagree with the parse, the parse check
    /// refuses the document.
    fn readings(self) -> &'static [Reading] {
        match self {
            Source::Value => &[Reading::Literal],
            Source::Text(Format::Json) => &[Reading::Escaped],
            Source::Text(Format::Yaml) => &[Reading::Escaped, Reading::Literal],
        }
    }
}

/// Rewrites strings that name the legacy root so they name the current one.
#[derive(Debug, Clone)]
pub struct RootRewrite {
    spellings: Vec<Spelling>,
    legacy_lower: String,
}

/// One spelling of the legacy root.
#[derive(Debug, Clone)]
struct Spelling {
    old: Vec<char>,
    /// Where the legacy author sits in `old`.
    author: Range<usize>,
    /// What replaces it.
    new_author: String,
}

/// The spellings of one root the rewrite matches: as given, and under
/// `canonical_base` when that spells the same base differently.
pub fn root_spellings(root: &AppRoot, canonical_base: Option<&Path>) -> Vec<AppRoot> {
    let mut roots = vec![root.clone()];
    if let Some(base) = canonical_base {
        let canonical = AppRoot::under(base);
        if canonical != *root {
            roots.push(canonical);
        }
    }
    roots
}

/// The base of `root` as `fs::canonicalize` spells it. The base still exists
/// after the move, so this works when the legacy folder no longer does.
pub fn canonical_base(root: &AppRoot) -> Option<PathBuf> {
    fs::canonicalize(root.current.parent()?.parent()?).ok()
}

/// The author folder's name as the disk spells it, read from the current
/// folder's canonical path (on Windows `fs::canonicalize` returns every
/// segment as it is stored). `None`, so [`APP_AUTHOR`] is written, unless that
/// path is `<canonical_base>\<author>\<app>` with an author that differs from
/// [`APP_AUTHOR`] in case alone: a link or any other shape is not this case,
/// and only letters ever replace the legacy author in a stored path.
pub fn author_on_disk(canonical_current: &Path, canonical_base: &Path) -> Option<String> {
    let author_dir = canonical_current.parent()?;
    let author = author_dir.file_name()?.to_str()?;
    (author_dir.parent()? == canonical_base
        && canonical_current.file_name()? == APP_NAME
        && author.eq_ignore_ascii_case(APP_AUTHOR))
    .then(|| author.to_string())
}

struct Found {
    /// Char index just past the match.
    end: usize,
    /// Char range of the author segment, in the text.
    author: Range<usize>,
}

impl RootRewrite {
    /// One spelling of one root.
    pub fn new(root: &AppRoot) -> Self {
        Self::for_roots(std::slice::from_ref(root))
    }

    /// Every spelling in `roots`, each writing [`APP_AUTHOR`]; at each
    /// position the first that matches wins (they all end at the same app
    /// segment).
    pub fn for_roots(roots: &[AppRoot]) -> Self {
        Self::with_authors(roots.iter().map(|root| (root, APP_AUTHOR)))
    }

    /// The rewrite a finished move runs for `root`: the environment's
    /// spelling writes [`APP_AUTHOR`], and the canonical spelling writes the
    /// author as the disk spells it ([`author_on_disk`]).
    pub fn after_move(root: &AppRoot) -> Self {
        let base = canonical_base(root);
        let on_disk = base
            .as_deref()
            .and_then(|base| author_on_disk(&fs::canonicalize(&root.current).ok()?, base));
        let roots = root_spellings(root, base.as_deref());
        Self::with_authors(roots.iter().enumerate().map(|(index, spelling)| {
            let author = match (index, &on_disk) {
                (0, _) | (_, None) => APP_AUTHOR,
                (_, Some(author)) => author.as_str(),
            };
            (spelling, author)
        }))
    }

    /// Each root with the author it writes. A spelling already listed keeps
    /// the author it was listed with.
    pub fn with_authors<'a>(roots: impl IntoIterator<Item = (&'a AppRoot, &'a str)>) -> Self {
        let mut spellings: Vec<Spelling> = Vec::new();
        for (root, author) in roots {
            let spelling = Spelling::of(root, author);
            if !spellings.iter().any(|known| known.old == spelling.old) {
                spellings.push(spelling);
            }
        }
        Self {
            spellings,
            legacy_lower: LEGACY_APP_AUTHOR.to_lowercase(),
        }
    }

    /// One parsed string value, or `None` when nothing in it names the legacy
    /// root.
    pub fn rewrite_str(&self, value: &str) -> Option<String> {
        self.rewrite(value, Source::Value)
    }

    fn rewrite(&self, text: &str, source: Source) -> Option<String> {
        if !text.to_lowercase().contains(&self.legacy_lower) {
            return None;
        }
        let chars: Vec<char> = text.chars().collect();
        let mut out = String::with_capacity(text.len());
        let mut copied = 0;
        let mut index = 0;
        let mut changed = false;
        while index < chars.len() {
            let found = source.readings().iter().find_map(|&reading| {
                if !starts_a_path(&chars, index, reading) {
                    return None;
                }
                self.spellings.iter().find_map(|spelling| {
                    spelling
                        .match_at(&chars, index, reading)
                        .map(|found| (found, spelling))
                })
            });
            if let Some((found, spelling)) = found {
                out.extend(&chars[copied..found.author.start]);
                out.push_str(&spelling.new_author);
                copied = found.author.end;
                index = found.end;
                changed = true;
            } else {
                index += 1;
            }
        }
        changed.then(|| {
            out.extend(&chars[copied..]);
            out
        })
    }

    /// Rewrite a document's text, checked against its parse. `Ok(None)` when
    /// nothing in it names the legacy root.
    pub fn rewrite_document(&self, text: &str, format: Format) -> Result<Option<String>, String> {
        let Some(rewritten) = self.rewrite(text, Source::Text(format)) else {
            return Ok(None);
        };
        let agrees = match format {
            Format::Json => {
                let mut expected: serde_json::Value =
                    serde_json::from_str(text).map_err(|error| format!("unreadable: {error}"))?;
                self.rewrite_json(&mut expected);
                serde_json::from_str::<serde_json::Value>(&rewritten).ok() == Some(expected)
            }
            Format::Yaml => {
                let mut expected: serde_yaml::Value =
                    serde_yaml::from_str(text).map_err(|error| format!("unreadable: {error}"))?;
                self.rewrite_yaml(&mut expected);
                serde_yaml::from_str::<serde_yaml::Value>(&rewritten).ok() == Some(expected)
            }
        };
        if agrees {
            Ok(Some(rewritten))
        } else {
            Err(
                "rewriting its text did not give the same document as rewriting its values, \
                 so it was left as it was"
                    .to_string(),
            )
        }
    }

    fn rewrite_json(&self, value: &mut serde_json::Value) {
        use serde_json::Value;
        match value {
            Value::String(text) => {
                if let Some(new) = self.rewrite_str(text) {
                    *text = new;
                }
            }
            Value::Array(items) => items.iter_mut().for_each(|item| self.rewrite_json(item)),
            Value::Object(map) => {
                let entries = std::mem::take(map);
                for (key, mut item) in entries {
                    self.rewrite_json(&mut item);
                    map.insert(self.rewrite_str(&key).unwrap_or(key), item);
                }
            }
            Value::Null | Value::Bool(_) | Value::Number(_) => {}
        }
    }

    fn rewrite_yaml(&self, value: &mut serde_yaml::Value) {
        use serde_yaml::Value;
        match value {
            Value::String(text) => {
                if let Some(new) = self.rewrite_str(text) {
                    *text = new;
                }
            }
            Value::Sequence(items) => items.iter_mut().for_each(|item| self.rewrite_yaml(item)),
            Value::Mapping(map) => {
                let entries = std::mem::take(map);
                for (mut key, mut item) in entries {
                    self.rewrite_yaml(&mut key);
                    self.rewrite_yaml(&mut item);
                    map.insert(key, item);
                }
            }
            Value::Tagged(tagged) => self.rewrite_yaml(&mut tagged.value),
            Value::Null | Value::Bool(_) | Value::Number(_) => {}
        }
    }
}

impl Spelling {
    fn of(root: &AppRoot, new_author: &str) -> Self {
        let old: Vec<char> = root.legacy.to_string_lossy().chars().collect();
        let app = APP_NAME.chars().count();
        let author_len = LEGACY_APP_AUTHOR.chars().count();
        let end = old.len() - app - 1;
        let author = end - author_len..end;
        debug_assert_eq!(
            old[author.clone()].iter().collect::<String>(),
            LEGACY_APP_AUTHOR
        );
        Self {
            old,
            author,
            new_author: new_author.to_string(),
        }
    }

    fn match_at(&self, chars: &[char], start: usize, reading: Reading) -> Option<Found> {
        let mut at = start;
        let mut author_start = at;
        let mut author_end = at;
        for (index, &expected) in self.old.iter().enumerate() {
            if index == self.author.start {
                author_start = at;
            }
            if index == self.author.end {
                author_end = at;
            }
            if is_separator(expected) {
                at = consume_separator(chars, at, reading)?;
            } else {
                if !same_letter(*chars.get(at)?, expected) {
                    return None;
                }
                at += 1;
            }
        }
        let bounded = unit_at(chars, at, reading).is_none_or(ends_a_segment);
        bounded.then_some(Found {
            end: at,
            author: author_start..author_end,
        })
    }
}

fn is_separator(c: char) -> bool {
    c == '\\' || c == '/'
}

fn consume_separator(chars: &[char], at: usize, reading: Reading) -> Option<usize> {
    let first = *chars.get(at)?;
    match reading {
        Reading::Literal => is_separator(first).then_some(at + 1),
        Reading::Escaped => match first {
            '/' => Some(at + 1),
            '\\' => chars
                .get(at + 1)
                .is_some_and(|second| is_separator(*second))
                .then_some(at + 2),
            _ => None,
        },
    }
}

/// Whether a path may start at `index`: not in the middle of a word, and,
/// when escapes are read, not in the middle of an escape.
fn starts_a_path(chars: &[char], index: usize, reading: Reading) -> bool {
    let before = match reading {
        Reading::Literal => index.checked_sub(1).map(|previous| chars[previous]),
        Reading::Escaped => {
            if escaped(chars, index) {
                return false;
            }
            unit_before(chars, index)
        }
    };
    before.is_none_or(|c| !c.is_alphanumeric())
}

/// Whether the character at `index` is the second one of an escape: an odd
/// run of backslashes sits right before it.
fn escaped(chars: &[char], index: usize) -> bool {
    chars[..index]
        .iter()
        .rev()
        .take_while(|c| **c == '\\')
        .count()
        % 2
        == 1
}

/// The character at `at`, read through an escape that starts there.
fn unit_at(chars: &[char], at: usize, reading: Reading) -> Option<char> {
    let c = *chars.get(at)?;
    if reading == Reading::Escaped && c == '\\' {
        // An escape no parser accepts leaves the document unreadable, and the
        // parse check refuses it; reading it as the separator it starts with
        // is as good as anything.
        return Some(escape_at(chars, at).map_or(c, |(decoded, _)| decoded));
    }
    Some(c)
}

/// The character just before `index`, read through an escape that ends there.
fn unit_before(chars: &[char], index: usize) -> Option<char> {
    let previous = *chars.get(index.checked_sub(1)?)?;
    // An escape's length is 2 (`\n`), 4 (`\xHH`), 6 (`\uHHHH`), 10
    // (`\UHHHHHHHH`) or 12 (a `\uHHHH\uHHHH` surrogate pair).
    for length in [2, 4, 6, 10, 12] {
        let Some(start) = index.checked_sub(length) else {
            break;
        };
        if chars[start] == '\\' && !escaped(chars, start) {
            if let Some((decoded, found)) = escape_at(chars, start) {
                if found == length {
                    return Some(decoded);
                }
            }
        }
    }
    Some(previous)
}

/// The escape that starts at `start` (a `\`), as JSON and double-quoted YAML
/// read it: the character it spells and how many characters it takes.
fn escape_at(chars: &[char], start: usize) -> Option<(char, usize)> {
    let short = match *chars.get(start + 1)? {
        c @ ('\\' | '/' | '"' | ' ') => c,
        'b' => '\u{8}',
        'f' => '\u{c}',
        'n' => '\n',
        'r' => '\r',
        't' | '\t' => '\t',
        '0' => '\0',
        'a' => '\u{7}',
        'v' => '\u{b}',
        'e' => '\u{1b}',
        'N' => '\u{85}',
        '_' => '\u{a0}',
        'L' => '\u{2028}',
        'P' => '\u{2029}',
        'x' => return Some((char::from_u32(hex(chars, start + 2, 2)?)?, 4)),
        'U' => return Some((char::from_u32(hex(chars, start + 2, 8)?)?, 10)),
        'u' => {
            let unit = hex(chars, start + 2, 4)?;
            if let Some(c) = char::from_u32(unit) {
                return Some((c, 6));
            }
            // A high surrogate, completed by the low one that follows it.
            let low = (chars.get(start + 6) == Some(&'\\') && chars.get(start + 7) == Some(&'u'))
                .then(|| hex(chars, start + 8, 4))
                .flatten()?;
            if !(0xD800..=0xDBFF).contains(&unit) || !(0xDC00..=0xDFFF).contains(&low) {
                return None;
            }
            let pair = 0x10000 + ((unit - 0xD800) << 10) + (low - 0xDC00);
            return Some((char::from_u32(pair)?, 12));
        }
        _ => return None,
    };
    Some((short, 2))
}

fn hex(chars: &[char], start: usize, digits: usize) -> Option<u32> {
    let text: String = chars.get(start..start + digits)?.iter().collect();
    if !text.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    u32::from_str_radix(&text, 16).ok()
}

fn same_letter(a: char, b: char) -> bool {
    a == b || a.to_lowercase().eq(b.to_lowercase())
}

/// Whether `next` can follow the legacy root in a path that is inside it: the
/// end of the string or of the value, or the next segment. Characters Windows
/// refuses in a name (`:`, `"`, `|`) and list separators (`;`, `,`) count too.
fn ends_a_segment(next: char) -> bool {
    is_separator(next)
        || next.is_whitespace()
        || next.is_control()
        || matches!(next, '"' | '\'' | ',' | ';' | ':' | '|' | ']' | '}')
}

/// What happened to one store.
#[derive(Debug)]
enum StoreResult {
    Absent,
    Unchanged,
    Rewritten,
    /// Read, but its content could not be rewritten safely. Not retried: the
    /// same content would fail the same way.
    Unverified(String),
    /// An I/O error. Retried at the next start.
    Failed(String),
}

/// What the rewrite found and did.
#[derive(Debug, Default)]
pub struct RewriteReport {
    pub files_rewritten: Vec<PathBuf>,
    pub session_rows_rewritten: usize,
    /// Stores left as they were because a safe rewrite was not possible.
    pub unverified: Vec<String>,
    /// Stores that could not be read or written; the marker stays so the next
    /// start tries again.
    pub failed: Vec<String>,
    pub marker_cleared: bool,
}

impl RewriteReport {
    pub(crate) fn log(&self) {
        if !self.files_rewritten.is_empty() || self.session_rows_rewritten > 0 {
            tracing::info!(
                files = ?self.files_rewritten,
                session_rows = self.session_rows_rewritten,
                "pointed stored paths at Biorouter's new folder after the move"
            );
        }
        for entry in &self.unverified {
            tracing::warn!(
                "left a stored path as it was after the folder move: {entry}. If an \
                 extension in it no longer starts, reinstall the extension."
            );
        }
        for entry in &self.failed {
            tracing::warn!(
                "could not update a stored path after the folder move: {entry}. It is tried \
                 again at the next start."
            );
        }
    }
}

/// Every JSON or YAML file the rewrite covers, under the current root. A
/// biorouter test pins each fixed name to the module that owns the store.
pub fn store_files(root: &Path) -> Vec<(PathBuf, Format)> {
    let config = root.join("config");
    let data = root.join("data");
    let mut files = vec![
        (config.join("config.yaml"), Format::Yaml),
        (config.join("knowledge").join("registry.yaml"), Format::Yaml),
        (config.join("daemon-profile.json"), Format::Json),
        (config.join("extension-provenance.json"), Format::Json),
        (config.join("crew").join("connections.json"), Format::Json),
        (config.join("headless").join("settings.json"), Format::Json),
        // Scoped approvals: a directory grant stores its canonical directory,
        // a command prefix grant the tokens it was given.
        (
            config.join("permissions").join("tool_permissions.json"),
            Format::Json,
        ),
        (data.join("schedule.json"), Format::Json),
        (data.join("projects.json"), Format::Json),
    ];
    files.extend(
        files_in(&config.join("extension-provenance.json.d"))
            .filter(|path| path.extension().is_some_and(|ext| ext == "json"))
            .map(|path| (path, Format::Json)),
    );
    // Install claims are JSON files named by the hex of the install id.
    files.extend(files_in(&config.join("extension-installs")).map(|path| (path, Format::Json)));
    for directory in [config.join("workflows"), data.join("scheduled_workflows")] {
        files.extend(files_in(&directory).filter_map(|path| {
            let format = match path.extension()?.to_str()? {
                "yaml" | "yml" => Format::Yaml,
                "json" => Format::Json,
                _ => return None,
            };
            Some((path, format))
        }));
    }
    files
}

/// The session database, under the current root.
pub fn sessions_db(root: &Path) -> PathBuf {
    root.join("data").join("sessions").join("sessions.db")
}

fn files_in(directory: &Path) -> impl Iterator<Item = PathBuf> {
    let mut files: Vec<PathBuf> = fs::read_dir(directory)
        .into_iter()
        .flatten()
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.is_file())
        .collect();
    files.sort();
    files.into_iter()
}

fn rewrite_file(rewrite: &RootRewrite, path: &Path, format: Format) -> StoreResult {
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return StoreResult::Absent,
        Err(error) if error.kind() == io::ErrorKind::InvalidData => {
            return StoreResult::Unverified(format!("{}: not UTF-8", path.display()))
        }
        Err(error) => return StoreResult::Failed(format!("{}: {error}", path.display())),
    };
    match rewrite.rewrite_document(&text, format) {
        Ok(None) => StoreResult::Unchanged,
        Ok(Some(new)) => match write_atomically(path, &new) {
            Ok(()) => StoreResult::Rewritten,
            Err(error) => StoreResult::Failed(format!("{}: {error}", path.display())),
        },
        Err(why) => StoreResult::Unverified(format!("{}: {why}", path.display())),
    }
}

fn write_atomically(path: &Path, contents: &str) -> io::Result<()> {
    let directory = path
        .parent()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "no parent directory"))?;
    let mut temp = tempfile::NamedTempFile::new_in(directory)?;
    temp.write_all(contents.as_bytes())?;
    temp.as_file().sync_all()?;
    #[cfg(unix)]
    {
        let permissions = fs::metadata(path)?.permissions();
        fs::set_permissions(temp.path(), permissions)?;
    }
    temp.persist(path).map_err(|error| error.error)?;
    Ok(())
}

/// Rule 3 for one roaming root whose current folder holds the marker. Clears
/// the marker once every store was read, whatever it held.
pub fn finish_pending_rewrite(root: &AppRoot) -> RewriteReport {
    let rewrite = RootRewrite::after_move(root);
    let mut report = RewriteReport::default();
    for (path, format) in store_files(&root.current) {
        match rewrite_file(&rewrite, &path, format) {
            StoreResult::Rewritten => report.files_rewritten.push(path),
            StoreResult::Unverified(why) => report.unverified.push(why),
            StoreResult::Failed(why) => report.failed.push(why),
            StoreResult::Absent | StoreResult::Unchanged => {}
        }
    }
    let db = sessions_db(&root.current);
    if db.exists() {
        match rewrite_sessions_db(&db, &rewrite) {
            Ok((rows, unverified)) => {
                report.session_rows_rewritten = rows;
                report.unverified.extend(unverified);
            }
            Err(why) => report.failed.push(format!("{}: {why}", db.display())),
        }
    }
    if report.failed.is_empty() {
        report.marker_cleared = match fs::remove_file(root.current.join(MOVE_MARKER)) {
            Ok(()) => true,
            Err(error) => error.kind() == io::ErrorKind::NotFound,
        };
    }
    report
}

/// The session columns that hold paths: the per-chat extension snapshot a
/// resume starts extensions from, the chat's workflow, and its working
/// directory (Crew task chats run inside the data folder).
const SESSION_COLUMNS: [(&str, Option<Format>); 3] = [
    ("extension_data", Some(Format::Json)),
    ("workflow_json", Some(Format::Json)),
    ("working_dir", None),
];

/// `sqlx` is async and the move runs inside the first resolver call, which may
/// itself be on a runtime thread, so the database work gets a thread and a
/// runtime of its own.
fn rewrite_sessions_db(db: &Path, rewrite: &RootRewrite) -> Result<(usize, Vec<String>), String> {
    let db = db.to_path_buf();
    let rewrite = rewrite.clone();
    std::thread::spawn(move || {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .map_err(|error| error.to_string())?
            .block_on(rewrite_sessions_db_async(&db, &rewrite))
            .map_err(|error| error.to_string())
    })
    .join()
    .map_err(|_| "the rewrite thread panicked".to_string())?
}

async fn rewrite_sessions_db_async(
    db: &Path,
    rewrite: &RootRewrite,
) -> Result<(usize, Vec<String>), sqlx::Error> {
    use sqlx::sqlite::SqliteConnectOptions;
    use sqlx::{Connection, Row};

    let options = SqliteConnectOptions::new()
        .filename(db)
        .create_if_missing(false)
        .busy_timeout(Duration::from_secs(10));
    let mut connection = sqlx::SqliteConnection::connect_with(&options).await?;
    let columns: Vec<String> = sqlx::query("SELECT name FROM pragma_table_info('sessions')")
        .fetch_all(&mut connection)
        .await?
        .iter()
        .map(|row| row.get::<String, _>(0))
        .collect();
    // SQLite's LIKE ignores ASCII case, matching the rewrite's own rule; the
    // filter only saves reading rows that cannot match.
    let pattern = format!("%{LEGACY_APP_AUTHOR}%");

    let mut rows_rewritten = 0;
    let mut unverified = Vec::new();
    let mut transaction = connection.begin().await?;
    for (column, format) in SESSION_COLUMNS {
        if !columns.iter().any(|name| name == column) {
            continue;
        }
        let rows = sqlx::query(&format!(
            "SELECT id, {column} FROM sessions WHERE {column} LIKE ?"
        ))
        .bind(&pattern)
        .fetch_all(&mut *transaction)
        .await?;
        for row in rows {
            let id: String = row.try_get(0)?;
            let value: String = row.try_get(1)?;
            let rewritten = match format {
                Some(format) => rewrite.rewrite_document(&value, format),
                None => Ok(rewrite.rewrite_str(&value)),
            };
            match rewritten {
                Ok(Some(new)) => {
                    sqlx::query(&format!("UPDATE sessions SET {column} = ? WHERE id = ?"))
                        .bind(new)
                        .bind(&id)
                        .execute(&mut *transaction)
                        .await?;
                    rows_rewritten += 1;
                }
                Ok(None) => {}
                Err(why) => unverified.push(format!("sessions.{column} of chat {id}: {why}")),
            }
        }
    }
    transaction.commit().await?;
    connection.close().await?;
    Ok((rows_rewritten, unverified))
}
