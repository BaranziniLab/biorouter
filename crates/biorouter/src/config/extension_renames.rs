//! The one map of extension ids Biorouter has renamed, `from` -> `to`.
//!
//! An extension's id is the `name_to_key` key of its config entry's name. It is
//! the prefix of every tool it offers (`gptr__r`), the key of its config entry,
//! the folder it is installed in and the key of its provenance record. Renaming
//! one therefore reaches stores that Biorouter does not own as current state:
//! saved chats keep their roster as configs, workflows and recipes name
//! extensions, transcripts and skills name tools, and `permission.yaml`, hooks
//! and managed policy name tools too.
//!
//! The rule is: the stores that describe what is installed NOW (the config
//! entry, the install folder, the provenance record) are moved once, at start,
//! by `extension_rename::migrate_on_start`. Every other store keeps the name it
//! was written with, and is RESOLVED through this map when it is read: a config
//! named `gptragent` loads as `gptr`, a call to `gptragent__r` runs `gptr__r`,
//! and a permission, hook or policy rule written for `gptragent__r` still
//! judges `gptr__r`.
//!
//! ⚠ **The map is not a privacy input.** Both names of a renamed private
//! extension are in the compiled private set (`privacy::registry_private`,
//! generated by `landing/scripts/build-registry.mjs`, which reads this same
//! JSON file to emit the second name). So a lookup that forgets to resolve a
//! name still classifies it Private; what it loses is routing, never the tier.
//!
//! ⚠ **One file, three readers.** `extension_renames.json` beside this file is
//! the table. This module reads it with `include_str!`; the BAAM generator
//! reads it from disk; the desktop app keeps a mirror in
//! `ui/desktop/src/utils/extensionRenames.ts`, pinned to the JSON by
//! `extensionRenames.test.ts`. Edit the JSON and the mirror together.
//!
//! A row is never removed: an old transcript, workflow or permission names the
//! old id for as long as it exists.

use std::borrow::Cow;
use std::path::Path;
use std::sync::LazyLock;

use serde::Deserialize;

use crate::agents::ExtensionConfig;

/// The table, compiled in. A malformed file fails `the_table_parses` in CI,
/// so the empty fallback in [`renames`] is never reached by a shipped build.
pub const RENAMES_JSON: &str = include_str!("extension_renames.json");

/// The only table version this build reads.
pub const RENAMES_VERSION: u32 = 1;

/// One rename. Both names are already `name_to_key` keys.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ExtensionRename {
    /// The id the extension had before. Never reused for anything else.
    pub from: String,
    /// The id it has now.
    pub to: String,
    /// Why, for a person reading the file. Not read by code.
    #[serde(default)]
    pub note: Option<String>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RenameTable {
    version: u32,
    renames: Vec<ExtensionRename>,
}

fn parse(text: &str) -> Result<Vec<ExtensionRename>, String> {
    let table: RenameTable = serde_json::from_str(text).map_err(|error| error.to_string())?;
    if table.version != RENAMES_VERSION {
        return Err(format!(
            "extension rename table version {} is not {RENAMES_VERSION}",
            table.version
        ));
    }
    validate(&table.renames)?;
    Ok(table.renames)
}

/// A name both reductions leave unchanged: `name_to_key` (whitespace stripped,
/// lowercased) and the extension manager's `normalize` (which also replaces
/// anything outside `[A-Za-z0-9_-]`). Only such a name can be a config key, a
/// tool prefix and a folder name at once.
fn is_stable_key(name: &str) -> bool {
    !name.is_empty()
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_' || b == b'-')
}

fn validate(renames: &[ExtensionRename]) -> Result<(), String> {
    for (index, rename) in renames.iter().enumerate() {
        for name in [&rename.from, &rename.to] {
            if !is_stable_key(name) {
                return Err(format!("`{name}` is not a stable extension key"));
            }
        }
        if rename.from == rename.to {
            return Err(format!("`{}` is renamed to itself", rename.from));
        }
        for other in renames.iter().skip(index + 1) {
            if other.from == rename.from {
                return Err(format!("`{}` is renamed twice", rename.from));
            }
            if other.to == rename.to {
                return Err(format!("two extensions are renamed to `{}`", rename.to));
            }
        }
        // No chains: a current id is never also an old id. A chain would make
        // "the current name" depend on how many times a lookup is applied.
        if renames.iter().any(|other| other.from == rename.to) {
            return Err(format!(
                "`{}` is both a current id and an old one; rename `{}` straight to the newest id",
                rename.to, rename.from
            ));
        }
    }
    Ok(())
}

static RENAMES: LazyLock<Vec<ExtensionRename>> = LazyLock::new(|| match parse(RENAMES_JSON) {
    Ok(renames) => renames,
    Err(error) => {
        tracing::error!(%error, "the compiled extension rename table is invalid; no old id resolves");
        Vec::new()
    }
});

/// Every rename, in table order.
pub fn renames() -> &'static [ExtensionRename] {
    RENAMES.as_slice()
}

/// The rename whose old id is `key`, if `key` is an old id.
pub fn rename_of(key: &str) -> Option<&'static ExtensionRename> {
    renames().iter().find(|rename| rename.from == key)
}

/// The id an extension known as `key` has now: `to` for an old id, `key`
/// itself otherwise. `key` must already be a `name_to_key` key.
pub fn current_key(key: &str) -> &str {
    match rename_of(key) {
        Some(rename) => rename.to.as_str(),
        None => key,
    }
}

/// The old ids of the extension whose current id is `key` (empty when it was
/// never renamed).
pub fn old_keys(key: &str) -> impl Iterator<Item = &'static str> + '_ {
    renames()
        .iter()
        .filter(move |rename| rename.to == key)
        .map(|rename| rename.from.as_str())
}

/// Every id the extension known as `key` has had: its current id first, then
/// its old ids. One element for an extension that was never renamed.
pub fn all_keys(key: &str) -> Vec<&str> {
    let current = current_key(key);
    let mut keys = vec![current];
    for old in old_keys(current) {
        keys.push(old);
    }
    keys
}

/// The prefix and the rest of a prefixed tool name, split at the FIRST `__`.
fn split_tool_name(name: &str) -> Option<(&str, &str)> {
    name.split_once("__")
}

/// The name a tool has now: `gptragent__r` becomes `gptr__r`. A name whose
/// prefix was never renamed, or that has no `__`, comes back unchanged.
pub fn current_tool_name(name: &str) -> Cow<'_, str> {
    match split_tool_name(name) {
        Some((prefix, rest)) => match rename_of(prefix) {
            Some(rename) => Cow::Owned(format!("{}__{rest}", rename.to)),
            None => Cow::Borrowed(name),
        },
        None => Cow::Borrowed(name),
    }
}

/// Every name a stored rule may have used for the tool `name`: its current
/// name first, then each old spelling. For a tool of an extension that was
/// never renamed, just `name`.
///
/// This is what a judge of tool names (a permission, a hook matcher, a managed
/// policy rule) tests, so a rule written before a rename keeps applying after
/// it, a deny included.
pub fn tool_name_aliases(name: &str) -> Vec<Cow<'_, str>> {
    let current = current_tool_name(name);
    let mut aliases: Vec<Cow<'_, str>> = Vec::new();
    if let Some((prefix, rest)) = split_tool_name(&current) {
        let olds: Vec<String> = old_keys(prefix)
            .map(|old| format!("{old}__{rest}"))
            .collect();
        aliases.push(current.clone());
        aliases.extend(olds.into_iter().map(Cow::Owned));
    } else {
        aliases.push(current.clone());
    }
    if !aliases.iter().any(|alias| alias.as_ref() == name) {
        aliases.push(Cow::Borrowed(name));
    }
    aliases
}

/// The rename an extension known as `key` belongs to, under either of its ids.
fn rename_touching(key: &str) -> Option<&'static ExtensionRename> {
    rename_of(key).or_else(|| renames().iter().find(|rename| rename.to == key))
}

/// Whether the install folder of `rename` has moved under `root`: the old
/// folder is gone and the new one is a directory. Before the move, and after a
/// move that failed or never ran, a stored path into the old folder is still
/// the right path, so it is left alone.
pub fn folder_moved(root: &Path, rename: &ExtensionRename) -> bool {
    let old_gone = matches!(
        std::fs::symlink_metadata(root.join(&rename.from)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound
    );
    old_gone && root.join(&rename.to).is_dir()
}

/// A config read from any store (`config.yaml`, a saved chat's roster, a
/// workflow, a subagent's profile), as this build loads it.
///
/// An extension whose key is an old id gets its current id as its name, so its
/// tools carry the current prefix. For a stdio config of either id, an argument
/// that names the old install folder as a path (the `uv run --directory <dir>`
/// that every installer writes; a trailing separator is the same path) becomes
/// the new folder once [`folder_moved`] says the move happened. Anything else is returned unchanged: built-in and
/// platform extensions are never renamed through this map, and an argument
/// that only resembles the folder is never rewritten.
///
/// `root` is the extensions folder (`extension_install::brxt::extensions_root()`
/// in production; a temporary directory in tests).
pub fn project_config_in(mut config: ExtensionConfig, root: &Path) -> ExtensionConfig {
    let key = config.key();
    let Some(rename) = rename_touching(&key) else {
        return config;
    };
    let rename_name = key == rename.from;
    let old_dir = root.join(&rename.from);
    let new_dir = root.join(&rename.to).display().to_string();
    let moved = folder_moved(root, rename);
    match &mut config {
        ExtensionConfig::Builtin { .. } | ExtensionConfig::Platform { .. } => {}
        ExtensionConfig::Stdio { name, args, .. } => {
            if rename_name {
                *name = rename.to.clone();
            }
            if moved {
                // As a path, not as a string: `<root>/gptragent/` is the same
                // folder, and the start migration judges it the same way.
                for arg in args.iter_mut() {
                    if Path::new(arg.as_str()) == old_dir {
                        arg.clone_from(&new_dir);
                    }
                }
            }
        }
        ExtensionConfig::Sse { name, .. }
        | ExtensionConfig::StreamableHttp { name, .. }
        | ExtensionConfig::Frontend { name, .. }
        | ExtensionConfig::InlinePython { name, .. } => {
            if rename_name {
                *name = rename.to.clone();
            }
        }
    }
    config
}

/// [`project_config_in`] against the real extensions folder.
pub fn project_config(config: ExtensionConfig) -> ExtensionConfig {
    project_config_in(config, &crate::extension_install::brxt::extensions_root())
}

/// [`project_config_in`] over a whole roster, without ever producing two
/// configs with one key: when the roster already holds the current id, a config
/// under the old id is left exactly as it was (both stay, both are private by
/// name, and the extension manager loads them under their own keys).
pub fn project_configs_in(configs: Vec<ExtensionConfig>, root: &Path) -> Vec<ExtensionConfig> {
    let keys: Vec<String> = configs.iter().map(ExtensionConfig::key).collect();
    configs
        .into_iter()
        .map(|config| {
            let key = config.key();
            match rename_of(&key) {
                Some(rename) if keys.contains(&rename.to) => config,
                _ => project_config_in(config, root),
            }
        })
        .collect()
}

/// [`project_configs_in`] against the real extensions folder.
pub fn project_configs(configs: Vec<ExtensionConfig>) -> Vec<ExtensionConfig> {
    project_configs_in(configs, &crate::extension_install::brxt::extensions_root())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::agents::extension::Envs;
    use crate::config::extensions::name_to_key;
    use std::path::PathBuf;

    fn stdio(name: &str, dir: &Path, entry_point: &str) -> ExtensionConfig {
        ExtensionConfig::Stdio {
            name: name.to_string(),
            description: String::new(),
            cmd: "uv".to_string(),
            args: vec![
                "run".to_string(),
                "--directory".to_string(),
                dir.display().to_string(),
                entry_point.to_string(),
            ],
            envs: Envs::default(),
            env_keys: Vec::new(),
            timeout: Some(300),
            bundled: None,
            available_tools: Vec::new(),
        }
    }

    fn args_of(config: &ExtensionConfig) -> Vec<String> {
        match config {
            ExtensionConfig::Stdio { args, .. } => args.clone(),
            _ => Vec::new(),
        }
    }

    #[test]
    fn an_old_config_loads_under_the_new_id_and_follows_a_moved_folder() {
        let root = tempfile::tempdir().unwrap();
        let old = root.path().join("gptragent");
        let new = root.path().join("gptr");
        std::fs::create_dir(&old).unwrap();

        // Before the move: renamed, and still pointed at the folder that exists.
        let before = project_config_in(stdio("GptrAgent", &old, "gptragent"), root.path());
        assert_eq!(before.key(), "gptr");
        assert_eq!(args_of(&before)[2], old.display().to_string());
        assert_eq!(
            args_of(&before)[3],
            "gptragent",
            "the entry point is the bundle's own"
        );

        // After the move: the folder argument follows it, under either id.
        std::fs::rename(&old, &new).unwrap();
        for name in ["gptragent", "gptr"] {
            let after = project_config_in(stdio(name, &old, "gptragent"), root.path());
            assert_eq!(after.key(), "gptr");
            assert_eq!(args_of(&after)[2], new.display().to_string());
        }

        // An argument that only resembles the old folder is never touched.
        let elsewhere = root.path().join("gptragent-copy");
        let kept = project_config_in(stdio("gptragent", &elsewhere, "gptragent"), root.path());
        assert_eq!(args_of(&kept)[2], elsewhere.display().to_string());

        // An extension that was never renamed is returned as it was.
        let other = stdio("spokeagent", &root.path().join("spokeagent"), "spokeagent");
        assert_eq!(project_config_in(other.clone(), root.path()), other);
    }

    /// The folder argument is compared as a path, as the start migration
    /// compares it: a spelling with a trailing separator names the same folder,
    /// and a projection that compared strings would leave it pointing at the
    /// folder the migration had just moved away.
    #[test]
    fn a_folder_argument_with_a_trailing_separator_follows_the_move_too() {
        let root = tempfile::tempdir().unwrap();
        let old = root.path().join("gptragent");
        let new = root.path().join("gptr");
        std::fs::create_dir(&new).unwrap();
        let trailing = PathBuf::from(format!("{}{}", old.display(), std::path::MAIN_SEPARATOR));
        let after = project_config_in(stdio("gptragent", &trailing, "gptragent"), root.path());
        assert_eq!(args_of(&after)[2], new.display().to_string());
    }

    #[test]
    fn a_roster_that_already_holds_the_new_id_keeps_its_old_entry_as_it_was() {
        let root = tempfile::tempdir().unwrap();
        let old = stdio("gptragent", &root.path().join("gptragent"), "gptragent");
        let new = stdio("gptr", &root.path().join("gptr"), "gptr");
        let projected = project_configs_in(vec![old.clone(), new.clone()], root.path());
        assert_eq!(projected, vec![old, new]);
    }

    #[test]
    fn the_table_parses() {
        let renames = parse(RENAMES_JSON).expect("extension_renames.json must parse and validate");
        assert_eq!(renames, renames_for_test());
    }

    /// The table stated once where a person reviews it. A row is never removed.
    fn renames_for_test() -> Vec<ExtensionRename> {
        vec![ExtensionRename {
            from: "gptragent".into(),
            to: "gptr".into(),
            note: Some(
                "gptr Agent's extension id, renamed with the owner's approval on 2026-11-28. \
                 The BAAM registry id stays gptragent."
                    .into(),
            ),
        }]
    }

    #[test]
    fn every_name_survives_both_key_reductions() {
        for rename in renames() {
            for name in [&rename.from, &rename.to] {
                assert_eq!(&name_to_key(name), name);
                assert!(is_stable_key(name), "{name}");
            }
        }
    }

    #[test]
    fn a_malformed_table_is_refused() {
        let bad = [
            r#"{"version":2,"renames":[]}"#,
            r#"{"version":1,"renames":[{"from":"a","to":"a"}]}"#,
            r#"{"version":1,"renames":[{"from":"a","to":"b"},{"from":"a","to":"c"}]}"#,
            r#"{"version":1,"renames":[{"from":"a","to":"c"},{"from":"b","to":"c"}]}"#,
            r#"{"version":1,"renames":[{"from":"a","to":"b"},{"from":"b","to":"c"}]}"#,
            r#"{"version":1,"renames":[{"from":"Gptr Agent","to":"gptr"}]}"#,
            r#"{"version":1,"renames":[{"from":"a","to":"b","extra":1}]}"#,
        ];
        for text in bad {
            assert!(parse(text).is_err(), "{text}");
        }
    }

    #[test]
    fn keys_resolve_one_way_and_list_every_name() {
        assert_eq!(current_key("gptragent"), "gptr");
        assert_eq!(current_key("gptr"), "gptr");
        assert_eq!(current_key("developer"), "developer");
        assert_eq!(all_keys("gptragent"), vec!["gptr", "gptragent"]);
        assert_eq!(all_keys("gptr"), vec!["gptr", "gptragent"]);
        assert_eq!(all_keys("developer"), vec!["developer"]);
    }

    #[test]
    fn a_tool_name_is_renamed_only_at_its_prefix() {
        assert_eq!(current_tool_name("gptragent__r"), "gptr__r");
        assert_eq!(current_tool_name("gptragent__a__b"), "gptr__a__b");
        assert_eq!(current_tool_name("gptr__r"), "gptr__r");
        assert_eq!(current_tool_name("gptragentx__r"), "gptragentx__r");
        assert_eq!(current_tool_name("x__gptragent__r"), "x__gptragent__r");
        assert_eq!(current_tool_name("gptragent"), "gptragent");
        assert_eq!(current_tool_name("r"), "r");
    }

    #[test]
    fn a_judge_tests_every_spelling_of_a_tool() {
        let names = |name: &str| -> Vec<String> {
            tool_name_aliases(name)
                .into_iter()
                .map(Cow::into_owned)
                .collect()
        };
        assert_eq!(names("gptr__r"), vec!["gptr__r", "gptragent__r"]);
        assert_eq!(names("gptragent__r"), vec!["gptr__r", "gptragent__r"]);
        assert_eq!(names("developer__shell"), vec!["developer__shell"]);
        assert_eq!(names("shell"), vec!["shell"]);
    }
}
